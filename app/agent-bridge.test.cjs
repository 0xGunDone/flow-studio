 const models=['omni-1.1-flash-edit-portrait','omni-1.1-flash','veo-3.1-fast-r2v-8s-landscape','veo-3.1-fast-i2v-8s-landscape','gemini-3.1-flash-image-landscape-4k'].map(id=>({id}));
